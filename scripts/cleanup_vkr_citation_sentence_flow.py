def replace_text_preserving_style(paragraph, text: str) -> None:
    clear_paragraph(paragraph)
    run = paragraph.add_run(text)
    set_run_font(run, 14)
    format_body(paragraph)


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Usage: cleanup_vkr_citation_sentence_flow.py <docx>")

    docx_path = Path(sys.argv[1])
    doc = Document(str(docx_path))
    changed = 0
    for paragraph in doc.paragraphs:
        text = paragraph.text or ""
        new_text = text
        for old, new in REPLACEMENTS.items():
            new_text = new_text.replace(old, new)
        if new_text != text:
            replace_text_preserving_style(paragraph, new_text)
            changed += 1
    doc.save(str(docx_path))
    set_update_fields_on_open(docx_path)
    print(f"Cleaned citation sentence flow: {changed} paragraphs")


if __name__ == "__main__":
    main()
