def remove_existing_generated_content(doc: Document) -> None:
    start_element = None
    for paragraph in doc.paragraphs:
        if paragraph.text.strip() == "Аннотация":
            start_element = paragraph._element
            break
    if start_element is None:
        return
    body = doc._body._element
    remove = False
    for element in list(body):
        if element is start_element:
            remove = True
        if remove and element.tag != qn("w:sectPr"):
            body.remove(element)


def remove_assignment_sheet(doc: Document) -> None:
    """Keep the title page and remove the original assignment sheet from the template."""
    start_after = None
    for paragraph in doc.paragraphs:
        if paragraph.text.strip() == "2026 г.":
            start_after = paragraph._element
            break
    if start_after is None:
        return

    body = doc._body._element
    remove = False
    for element in list(body):
        if remove and element.tag != qn("w:sectPr"):
            body.remove(element)
            continue
        if element is start_after:
            remove = True


def main() -> None:
    if not DOCX_PATH.exists():
        raise FileNotFoundError(DOCX_PATH)
    doc = Document(str(DOCX_PATH))
    style_document(doc)
    remove_existing_generated_content(doc)
    remove_assignment_sheet(doc)

    add_page_break(doc)
    add_annotation(doc)

    add_heading(doc, "Содержание", 1)
    add_static_toc(doc)
    add_page_break(doc)

