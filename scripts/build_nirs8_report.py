    add_p(doc, "При D_кр = 1 показатель HI находится в диапазоне от 1 до 0. Значение HI = 1 соответствует исправному узлу, HI = 0 соответствует предельному состоянию. Для практической интерпретации вводятся три зоны: исправная зона HI > 0,5, предупредительная зона 0,25 < HI <= 0,5 и критическая зона HI <= 0,25.")

