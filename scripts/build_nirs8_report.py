    add_heading(doc, "4.7 Выводы по техническому проектированию", 2)
    add_p(doc, "В главе разработана математическая модель накопления повреждений, введён показатель Health Index, определена связь модели с диагностическими признаками и задан критерий предельного состояния. Тем самым выполнены третья и четвёртая задачи задания.")


