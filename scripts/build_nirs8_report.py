def add_table(doc: Document, key: str) -> None:
    spec = TABLES[key]
    cap = doc.add_paragraph(spec["caption"])
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.first_line_indent = Cm(0)
    for run in cap.runs:
        run.font.name = "Times New Roman"
        run.font.size = Pt(BODY_FONT_PT)
        run.bold = True

    table = doc.add_table(rows=1, cols=len(spec["headers"]))
    table.style = "Table Grid"
    for idx, header in enumerate(spec["headers"]):
        set_cell_text(table.rows[0].cells[idx], header)
        for run in table.rows[0].cells[idx].paragraphs[0].runs:
            run.bold = True
    for row in spec["rows"]:
        cells = table.add_row().cells
        for idx, value in enumerate(row):
            set_cell_text(cells[idx], value)


def add_toc(paragraph) -> None:
    paragraph.paragraph_format.first_line_indent = Cm(0)
    run = paragraph.add_run()
    fld_begin = OxmlElement("w:fldChar")
    fld_begin.set(qn("w:fldCharType"), "begin")
    instr = OxmlElement("w:instrText")
    instr.set(qn("xml:space"), "preserve")
    instr.text = 'TOC \\o "1-2" \\h \\z \\u'
    fld_sep = OxmlElement("w:fldChar")
    fld_sep.set(qn("w:fldCharType"), "separate")
    fld_text = OxmlElement("w:t")
    fld_text.text = "Оглавление обновляется в Microsoft Word."
    fld_end = OxmlElement("w:fldChar")
    fld_end.set(qn("w:fldCharType"), "end")
    run._r.extend([fld_begin, instr, fld_sep, fld_text, fld_end])


def set_update_fields_on_open(doc: Document) -> None:
    settings = doc.settings.element
    update_fields = settings.find(qn("w:updateFields"))
    if update_fields is None:
        update_fields = OxmlElement("w:updateFields")
        settings.append(update_fields)
    update_fields.set(qn("w:val"), "true")


