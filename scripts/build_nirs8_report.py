def set_cell_text(cell, text: str) -> None:
    cell.text = text
    for paragraph in cell.paragraphs:
        paragraph.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
        paragraph.paragraph_format.first_line_indent = Cm(0)
        for run in paragraph.runs:
            run.font.name = "Times New Roman"
            run.font.size = Pt(BODY_FONT_PT)


def style_document(doc: Document) -> None:
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(3)
    section.right_margin = Cm(1.5)

    normal = doc.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(BODY_FONT_PT)
    normal.paragraph_format.first_line_indent = Cm(1.25)
    normal.paragraph_format.line_spacing = None
    normal.paragraph_format.space_after = Pt(0)
    normal.paragraph_format.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY

    for style_name in ["Heading 1", "Heading 2", "Heading 3"]:
        if style_name not in [style.name for style in doc.styles]:
            doc.styles.add_style(style_name, WD_STYLE_TYPE.PARAGRAPH)
        style = doc.styles[style_name]
        style.font.name = "Times New Roman"
        style.font.bold = True
        style.font.color.rgb = RGBColor(0, 0, 0)
        style.paragraph_format.first_line_indent = Cm(0)
        style.paragraph_format.space_before = Pt(12)
        style.paragraph_format.space_after = Pt(6)
        style.paragraph_format.line_spacing = None

    doc.styles["Heading 1"].font.size = Pt(BODY_FONT_PT)
    doc.styles["Heading 2"].font.size = Pt(BODY_FONT_PT)
    doc.styles["Heading 3"].font.size = Pt(BODY_FONT_PT)

    if "List Paragraph" not in [style.name for style in doc.styles]:
        list_style = doc.styles.add_style("List Paragraph", WD_STYLE_TYPE.PARAGRAPH)
        list_style.font.name = "Times New Roman"
        list_style.font.size = Pt(BODY_FONT_PT)


