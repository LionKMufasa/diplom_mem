    add_p(doc, "Связь параметров деградации с диагностическими признаками реализуется через коэффициенты K_M и K_a. Рост M_rms указывает на повышение сопротивления движению, рост M_max - на перегрузки или ударные режимы, увеличение E - на рост энергетических затрат на выполнение одной и той же операции. Если при одинаковой фазе цикла признаки имеют устойчивый положительный тренд, это интерпретируется как ухудшение технического состояния.")

    add_heading(doc, "4.6 Критерий предельного состояния узла", 2)
    add_p(doc, "Предельное состояние узла задаётся условием:")
