    add_p(doc, "Для технического проектирования модели используется набор признаков, который может быть получен из имитационной модели и в дальнейшем расширен при наличии промышленных датчиков. Основные параметры наблюдения: момент M(t), угловая скорость omega(t), ускорение a(t), длительность фазы и номер рабочего цикла N.")
    add_p(doc, "Для каждой оси и фазы цикла рассчитываются M_rms, M_max, E, a_rms и производный тренд признака. Такой набор отражает как статическую нагруженность, так и динамический характер движения.")

    add_heading(doc, "4.2 Математическая модель накопления повреждений во времени", 2)
    add_p(doc, "Накопленное повреждение i-го узла обозначается D_i(N), где N - число рабочих циклов. Начальное состояние задаётся D_i(0) = D_0. При каждом цикле повреждение увеличивается на величину, зависящую от базовой скорости деградации и нагрузочных коэффициентов:")
    add_formula(doc, "D_i(N + 1) = D_i(N) + k_0 * K_M * K_a * K_T")
    add_p(doc, "где k_0 - базовый коэффициент деградации за один цикл; K_M - коэффициент влияния момента; K_a - коэффициент влияния ускорений; K_T - коэффициент, учитывающий температурные и эксплуатационные условия. Для исследовательской модели K_T принимается равным 1, если дополнительные условия не измеряются.")

    add_heading(doc, "4.3 Учёт нагрузки и режима движения в скорости деградации", 2)
