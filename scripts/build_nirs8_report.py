    add_formula(doc, "K_M = (M_rms / M_ref)^alpha")
    add_p(doc, "где M_ref - базовый момент исправного узла, alpha - показатель чувствительности деградации к нагрузке. Для механических узлов, работающих в режиме износа с возрастающей интенсивностью, принимается alpha = 2. Коэффициент ускорений определяется как:")
